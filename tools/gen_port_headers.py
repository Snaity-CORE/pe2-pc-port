#!/usr/bin/env python3
"""Generate the PC version of the decomp's GTE command header.

The decomp's `gte.h` drives the GTE with inline MIPS assembly (command
words). This tool reads it from the `decomp/` submodule and rewrites every
`__asm__` macro body as equivalent C on top of the software GTE in
`port/include/pc/gte.h`. Everything else in the header is kept as is. The
register loads and stores it builds on come from the port's own
`port/include/psyq/inline_c.h`.

The output goes to `build/port_include/` and is never committed: it is
derived from the decomp's header, so it is regenerated on each build like
any other build artifact.

Supported instructions are the ones the header uses: lwc2/swc2, mtc2/mfc2,
ctc2/cfc2, lw/lh/lhu/lb/lbu, sw/sh/sb, sll/sra/srl, addu/subu/or/and,
addi/addiu, nop, and `.word` COP2 command words.
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECOMP = ROOT / "decomp"

# (source header relative to decomp/, output path relative to the out dir)
HEADERS = [
    ("include/decomp/gte.h", "gte.h"),
]

# GTE macros the decomp defines locally inside .c files rather than in a
# header: (source file, macro name, output header it is appended to). The fork
# guards those local definitions with `#ifndef PC_PORT`, so the translated copy
# here is the one native builds see. gte_RotTransLV has four identical copies
# (actor_render.c, ending.c, model_lighting.c, model_objects.c); the last one
# spells its command words as "i" operands, with the same values.
EXTRA_MACROS = [
    ("src/gameplay/actor_render.c", "gte_RotTransLV", "gte.h"),
]

DEFINE_RE = re.compile(r"#define\s+(\w+)\s*\(([^)]*)\)\s*__asm__\s*(?:volatile|__volatile__)?\s*\(", re.S)
# offset(base): the offset is a literal or an "i" operand (%n).
MEM_RE = re.compile(r"^(-?\w+|%\d+)?\s*\(\s*([%$]\w+)\s*\)$")

LOADS = {"lw": "PCMEM_LW", "lh": "PCMEM_LH", "lhu": "PCMEM_LHU", "lb": "PCMEM_LB", "lbu": "PCMEM_LBU"}
STORES = {"sw": "PCMEM_SW", "sh": "PCMEM_SH", "sb": "PCMEM_SB"}
ALU3 = {"addu": "+", "subu": "-", "or": "|", "and": "&", "xor": "^"}
# Logical immediates zero-extend their 16-bit operand.
ALU_IMM_LOGICAL = {"andi": "&", "ori": "|", "xori": "^"}
SHIFTS = {"sll": "<<", "srl": ">>"}

PRELUDE = """\
/* GENERATED by tools/gen_port_headers.py from decomp/{src}. Do not edit. */
#include "pc/gte_macros.h"
"""


class TranslateError(Exception):
    pass


def split_top(text: str, sep: str) -> list[str]:
    """Split on `sep` outside string literals and parentheses."""
    parts, depth, cur, in_str, i = [], 0, [], False, 0
    while i < len(text):
        c = text[i]
        if in_str:
            cur.append(c)
            if c == "\\":
                cur.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            cur.append(c)
        elif c == "(":
            depth += 1
            cur.append(c)
        elif c == ")":
            depth -= 1
            cur.append(c)
        elif c == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        i += 1
    parts.append("".join(cur))
    return parts


def find_close(text: str, start: int) -> int:
    """Index of the parenthesis closing the one opened just before `start`."""
    depth, in_str, i = 1, False, start
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise TranslateError("unbalanced parentheses")


def parse_operands(section: str) -> list[tuple[str, str]]:
    ops = []
    for part in split_top(section, ","):
        part = part.strip()
        if not part:
            continue
        m = re.match(r'"([^"]*)"\s*\((.*)\)$', part, re.S)
        if not m:
            raise TranslateError(f"bad operand {part!r}")
        ops.append((m.group(1), m.group(2).strip()))
    return ops


class Translator:
    def __init__(self, outputs, inputs):
        self.operands = outputs + inputs
        self.n_out = len(outputs)
        self.gprs: set[int] = set()
        self.lines: list[str] = []

    def gpr(self, tok: str) -> str:
        """A value operand: %n (macro operand) or $n (temporary GPR)."""
        if tok.startswith("%"):
            return f"_a{int(tok[1:])}"
        n = int(tok[1:])
        if n == 0:
            return "0u"
        self.gprs.add(n)
        return f"_r{n}"

    def dest(self, tok: str) -> str:
        if tok.startswith("%"):
            idx = int(tok[1:])
            if idx >= self.n_out:
                raise TranslateError(f"write to input operand {tok}")
            return f"_a{idx}"
        n = int(tok[1:])
        if n == 0:
            raise TranslateError("write to $0")
        self.gprs.add(n)
        return f"_r{n}"

    def addr(self, mem: str) -> str:
        m = MEM_RE.match(mem.replace(" ", ""))
        if not m:
            raise TranslateError(f"bad memory operand {mem!r}")
        off, base = m.groups()
        if off and off.startswith("%"):
            return f"({self.gpr(base)} + {self.gpr(off)})"
        off = int(off, 0) if off else 0
        return f"({self.gpr(base)} + {off})" if off else self.gpr(base)

    @staticmethod
    def cop2(tok: str) -> int:
        if not tok.startswith("$"):
            raise TranslateError(f"bad cop2 register {tok}")
        return int(tok[1:])

    def emit(self, insn: str) -> None:
        insn = insn.strip()
        if not insn or insn == "nop":
            return
        m = re.match(r"(\.?\w+)\s*(.*)$", insn)
        op, rest = m.group(1), m.group(2)
        args = [a.strip() for a in split_top(rest, ",")] if rest else []
        out = self.lines.append

        if op == ".word" and args[0].startswith("%"):
            constraint = self.operands[int(args[0][1:])][0]
            if constraint == "i":
                # A real COP2 command word passed as an immediate operand.
                out(f"pcgte_op((uint32_t){self.gpr(args[0])});")
            else:
                # gte_mvmva_core: a DMPSX MVMVA placeholder assembled at run
                # time from its sf/mx/v/cv/lm fields; decoded by the GTE.
                out(f"pcgte_op_dmpsx_mvmva((uint32_t){self.gpr(args[0])});")
        elif op == ".word":
            word = int(args[0], 0)
            if word >> 25 == 0x25:  # COP2 command (0x4A000000 | imm25)
                out(f"pcgte_op(0x{word:08X}u);")
            elif word < 0x01000000:
                # DMPSX placeholder: Psy-Q's inline_c.h emits these for the
                # commands, and the decomp's gte.h redefines every one the game
                # uses with the real word. A placeholder that survives would be
                # a silent no-op, so make it fail to link instead.
                out(f"pcgte_untranslated_dmpsx_placeholder_0x{word:X}();")
            else:
                raise TranslateError(f".word {args[0]} is not a GTE command")
        elif op == "lwc2":
            out(f"pcgte_write_data({self.cop2(args[0])}, PCMEM_LW({self.addr(args[1])}));")
        elif op == "swc2":
            out(f"PCMEM_SW({self.addr(args[1])}, pcgte_read_data({self.cop2(args[0])}));")
        elif op == "mtc2":
            out(f"pcgte_write_data({self.cop2(args[1])}, (uint32_t)({self.gpr(args[0])}));")
        elif op == "ctc2":
            out(f"pcgte_write_ctrl({self.cop2(args[1])}, (uint32_t)({self.gpr(args[0])}));")
        elif op == "mfc2":
            out(f"{self.dest(args[0])} = pcgte_read_data({self.cop2(args[1])});")
        elif op == "cfc2":
            out(f"{self.dest(args[0])} = pcgte_read_ctrl({self.cop2(args[1])});")
        elif op in LOADS:
            out(f"{self.dest(args[0])} = (uint32_t){LOADS[op]}({self.addr(args[1])});")
        elif op in STORES:
            out(f"{STORES[op]}({self.addr(args[1])}, {self.gpr(args[0])});")
        elif op in SHIFTS:
            out(f"{self.dest(args[0])} = (uint32_t){self.gpr(args[1])} {SHIFTS[op]} {int(args[2], 0)};")
        elif op == "sra":
            out(f"{self.dest(args[0])} = (uint32_t)((int32_t){self.gpr(args[1])} >> {int(args[2], 0)});")
        elif op in ALU3:
            out(f"{self.dest(args[0])} = (uint32_t){self.gpr(args[1])} {ALU3[op]} (uint32_t){self.gpr(args[2])};")
        elif op in ("addi", "addiu"):
            out(f"{self.dest(args[0])} = (uint32_t){self.gpr(args[1])} + (uint32_t)({int(args[2], 0)});")
        elif op in ALU_IMM_LOGICAL:
            imm = int(args[2], 0) & 0xFFFF
            out(f"{self.dest(args[0])} = (uint32_t){self.gpr(args[1])} {ALU_IMM_LOGICAL[op]} 0x{imm:X}u;")
        elif op == "slt":
            out(f"{self.dest(args[0])} = (int32_t){self.gpr(args[1])} < (int32_t){self.gpr(args[2])};")
        elif op == "sltu":
            out(f"{self.dest(args[0])} = (uint32_t){self.gpr(args[1])} < (uint32_t){self.gpr(args[2])};")
        else:
            raise TranslateError(f"unsupported instruction {insn!r}")

    def render(self, params: str) -> str:
        decls = []
        for i, (constraint, expr) in enumerate(self.operands):
            if constraint.startswith("="):
                decls.append(f"uint32_t _a{i};")
            else:
                decls.append(f"uintptr_t _a{i} = (uintptr_t)({expr});")
        decls += [f"uint32_t _r{n};" for n in sorted(self.gprs)]
        writeback = [f"{expr} = _a{i};" for i, (c, expr) in enumerate(self.operands) if c.startswith("=")]
        body = decls + self.lines + writeback
        if body:
            joined = " \\\n    ".join(body)
            return f"do {{ \\\n    {joined} \\\n}} while (0)"
        return "do { } while (0)"


def translate_asm(body: str, params: str) -> str:
    sections = split_top(body, ":")
    asm = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', sections[0]))
    outputs = parse_operands(sections[1]) if len(sections) > 1 else []
    inputs = parse_operands(sections[2]) if len(sections) > 2 else []
    t = Translator(outputs, inputs)
    for insn in re.split(r"[;\n]|\\n", asm):
        t.emit(insn)
    return t.render(params)


def convert(text: str) -> tuple[str, int]:
    out, pos, count = [], 0, 0
    # Work on the text with line continuations joined so a macro is one line.
    text = text.replace("\\\r\n", " ").replace("\\\n", " ")
    for m in DEFINE_RE.finditer(text):
        close = find_close(text, m.end())
        name, params = m.group(1), m.group(2)
        try:
            body = translate_asm(text[m.end():close], params)
        except TranslateError as e:
            raise TranslateError(f"{name}: {e}") from None
        out.append(text[pos:m.start()])
        out.append(f"#define {name}({params}) {body}")
        pos = close + 1
        count += 1
    out.append(text[pos:])
    return "".join(out), count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "build" / "port_include")
    args = parser.parse_args()

    outputs: dict[str, str] = {}
    for src, dst in HEADERS:
        text = (DECOMP / src).read_text(encoding="utf-8")
        converted, count = convert(text)
        if "__asm__" in converted:
            raise SystemExit(f"{src}: __asm__ left after conversion")
        outputs[dst] = PRELUDE.format(src=src) + converted
        print(f"{dst}: {count} macros")

    for src, name, dst in EXTRA_MACROS:
        macro = extract_macro((DECOMP / src).read_text(encoding="utf-8"), name, src)
        # Appended after the header's own include guard closes.
        outputs[dst] += f"\n/* {name}: translated from decomp/{src} (defined locally there). */\n"
        outputs[dst] += f"#ifndef {name}\n{macro}\n#endif\n"
        print(f"{dst}: + {name} from {src}")

    for dst, content in outputs.items():
        target = args.out / dst
        target.parent.mkdir(parents=True, exist_ok=True)
        # Leave unchanged headers alone so dependent objects are not rebuilt.
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")


def extract_macro(text: str, name: str, src: str) -> str:
    """Translate the asm macro `name` defined in `text` into a C #define."""
    text = text.replace("\\\r\n", " ").replace("\\\n", " ")
    for m in DEFINE_RE.finditer(text):
        if m.group(1) == name:
            close = find_close(text, m.end())
            try:
                body = translate_asm(text[m.end():close], m.group(2))
            except TranslateError as e:
                raise SystemExit(f"{src}: {name}: {e}") from None
            return f"#define {name}({m.group(2)}) {body}"
    raise SystemExit(f"{src}: asm macro {name} not found")


if __name__ == "__main__":
    main()
